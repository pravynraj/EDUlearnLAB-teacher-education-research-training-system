"""Data processing and descriptive analytics (pandas / NumPy).

Only descriptive statistics are produced here. No inferential claims are made;
comparisons or correlations should be added only when justified by real data.
"""
import numpy as np
import pandas as pd
from questionnaire import DOMAINS, ITEM_CODES, ITEM_TEXT, LIKERT

VALID_SOURCES = ("all", "collected", "synthetic", "imported")


def load_wide(conn, source="all", category=None, practicum=None):
    """Return a wide DataFrame: one row per respondent, one column per item."""
    where, params = [], []
    if source in ("collected", "synthetic", "imported"):
        where.append("r.source = ?"); params.append(source)
    if category:
        where.append("r.category = ?"); params.append(category)
    if practicum:
        where.append("r.practicum_status = ?"); params.append(practicum)
    clause = ("WHERE " + " AND ".join(where)) if where else ""
    meta = pd.read_sql_query(
        f"SELECT r.id, r.created_at, r.source, r.category, r.practicum_status, r.ai_exposure "
        f"FROM respondents r {clause} ORDER BY r.id", conn, params=params)
    if meta.empty:
        return meta.assign(**{c: pd.Series(dtype=float) for c in ITEM_CODES})
    items = pd.read_sql_query(
        f"SELECT i.respondent_id, i.item_code, i.score FROM item_responses i "
        f"JOIN respondents r ON r.id = i.respondent_id {clause}", conn, params=params)
    wide = items.pivot(index="respondent_id", columns="item_code", values="score")
    wide = wide.reindex(columns=ITEM_CODES)
    return meta.merge(wide, left_on="id", right_index=True, how="left")


def cronbach_alpha(df):
    """Cronbach's alpha for a respondents x items frame; None if not computable."""
    data = df.dropna()
    n, k = data.shape
    if n < 10 or k < 2:
        return None
    total_var = data.sum(axis=1).var(ddof=1)
    if not total_var or np.isnan(total_var):
        return None
    return float(k / (k - 1) * (1 - data.var(ddof=1).sum() / total_var))


def _r(x, nd=2):
    return None if x is None or (isinstance(x, float) and np.isnan(x)) else round(float(x), nd)


def domain_summary(wide):
    rows = []
    for d in DOMAINS:
        cols = [f"{d['code']}{i}" for i in range(1, len(d["items"]) + 1)]
        block = wide[cols]
        scores = block.to_numpy(dtype=float).ravel()
        scores = scores[~np.isnan(scores)]
        per_person = block.mean(axis=1)
        n = int(per_person.notna().sum())
        rows.append({
            "code": d["code"], "name": d["name"], "color": d["color"], "n": n,
            "mean": _r(per_person.mean()) if n else None,
            "sd": _r(per_person.std(ddof=1)) if n > 1 else None,
            "pct_agree": _r((scores >= 4).mean() * 100, 1) if scores.size else None,
            "pct_neutral": _r((scores == 3).mean() * 100, 1) if scores.size else None,
            "pct_low": _r((scores <= 2).mean() * 100, 1) if scores.size else None,
            "alpha": _r(cronbach_alpha(block), 2),
        })
    return rows


def distributions(wide):
    out = {"overall": {}, "by_domain": {}}
    allv = wide[ITEM_CODES].to_numpy(dtype=float).ravel()
    allv = allv[~np.isnan(allv)]
    out["overall"] = {str(k): int((allv == k).sum()) for k in LIKERT}
    for d in DOMAINS:
        cols = [f"{d['code']}{i}" for i in range(1, len(d["items"]) + 1)]
        v = wide[cols].to_numpy(dtype=float).ravel(); v = v[~np.isnan(v)]
        out["by_domain"][d["code"]] = {str(k): int((v == k).sum()) for k in LIKERT}
    return out


def item_summary(wide):
    res = []
    for code in ITEM_CODES:
        s = wide[code].dropna()
        res.append({"code": code, "text": ITEM_TEXT[code], "n": int(s.size),
                    "mean": _r(s.mean()) if s.size else None,
                    "sd": _r(s.std(ddof=1)) if s.size > 1 else None})
    return res


def describe_source(wide):
    if wide.empty:
        return {"kind": "none", "label": "No responses match the current filter."}
    kinds = sorted(wide["source"].unique())
    if kinds == ["synthetic"]:
        return {"kind": "synthetic", "label": "SYNTHETIC DEMONSTRATION DATA. Generated by seed_demo.py. "
                "These are not real participants and are not research findings."}
    if kinds == ["collected"]:
        return {"kind": "collected", "label": "Data collected through the TeacherEdLab questionnaire form."}
    if kinds == ["imported"]:
        return {"kind": "imported", "label": "Data imported from CSV by a researcher."}
    return {"kind": "mixed", "label": "MIXED DATA: " + ", ".join(kinds) +
            ". Filter by data source before interpreting any figure."}


def build_dashboard(conn, source="all", category=None, practicum=None):
    wide = load_wide(conn, source, category, practicum)
    domains = domain_summary(wide) if len(wide) else []
    ranked = sorted([d for d in domains if d["mean"] is not None], key=lambda d: d["mean"])
    cats = wide["category"].value_counts().to_dict() if len(wide) else {}
    prac = wide["practicum_status"].value_counts().to_dict() if len(wide) else {}
    return {
        "n_responses": int(len(wide)),
        "data_source": describe_source(wide),
        "filters": {"source": source, "category": category, "practicum": practicum},
        "domains": domains,
        "distribution": distributions(wide) if len(wide) else {"overall": {}, "by_domain": {}},
        "items": item_summary(wide) if len(wide) else [],
        "by_category": cats, "by_practicum": prac,
        "lowest_domain": ranked[0]["name"] if ranked else None,
        "highest_domain": ranked[-1]["name"] if ranked else None,
        "alpha_note": "Cronbach's alpha is computed from the filtered data when n >= 10. "
                      "For synthetic data it describes the generator, not a real instrument.",
    }
